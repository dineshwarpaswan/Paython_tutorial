print("\nLooping Through a Tuple basically means accessing all its items one-by-one.\n")

brand = ("Leptop","Mobile","Desktop","Moniter") # only string data
print("\nThis is a Tuple:",brand)

for b in brand:
    print(b) # accessing all items one-by-one and will be print
	
	
mix = ("Dog",50,"Fruit",30.01,True,"Mobile") # mixture data 
print("\nThis is a Tuple:",mix)

for data in mix:
    print("\nAccessing All Items : ",data) # accessing all items one-by-one and will be print